/** Normalises a Kenyan mobile number to 2547XXXXXXXX / 2541XXXXXXXX, or null if invalid. */
export const toMpesaPhone = (raw: string): string | null => {
  const d = raw.replace(/[^\d]/g, '');
  if (/^254[17]\d{8}$/.test(d)) return d;
  if (/^0[17]\d{8}$/.test(d)) return `254${d.slice(1)}`;
  if (/^[17]\d{8}$/.test(d)) return `254${d}`;
  return null;
};
